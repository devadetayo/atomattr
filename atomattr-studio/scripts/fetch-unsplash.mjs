// Downloads the Unsplash photos used by the templates and embeds them in src/document/unsplash.ts.
// Run once, from the project folder, with internet:  node scripts/fetch-unsplash.mjs   (Node 18+)
import { writeFileSync } from 'node:fs';
const ID = {
  saasHero: ['1551288049-bebda4e38f71', 1200], dashboard: ['1507238691740-187a5b1d37b8', 1200], teamwork: ['1522071820081-009f0129c71c', 1200], appScreen: ['1616469829941-c7200edec809', 1200],
  fashionHero: ['1483985988355-763728e1935b', 1200], financeHero: ['1563986768609-322da13575f3', 1200], mortgageAgent: ['1560250097-0b93528c311a', 800],
  customer1: ['1573496359142-b8d87734a5a2', 800], customer2: ['1580489944761-15a19d654956', 800], realEstateHero: ['1600596542815-ffad4c1539a9', 1200], interior: ['1618221195710-dd6b41faaea6', 800],
};
const out = {};
for (const [key, [id, w]] of Object.entries(ID)) {
  try {
    const res = await fetch(`https://images.unsplash.com/photo-${id}?q=75&w=${w}&auto=format&fit=crop`);
    if (!res.ok) throw new Error(String(res.status));
    out[key] = `data:image/jpeg;base64,${Buffer.from(await res.arrayBuffer()).toString('base64')}`;
    console.log('ok  ', key);
  } catch (e) { console.log('FAIL', key, e.message); }
}
writeFileSync('src/document/unsplash.ts', `/* Generated by scripts/fetch-unsplash.mjs */\nexport const UNSPLASH: Record<string, string> = ${JSON.stringify(out, null, 0)};\n`);
console.log(`Saved ${Object.keys(out).length} photos. Restart the dev server.`);
